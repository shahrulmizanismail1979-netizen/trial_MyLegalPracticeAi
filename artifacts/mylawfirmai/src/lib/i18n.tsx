const dictionaries: Record<Lang, Dict> = { en, ms };

type LanguageContextType = {
  lang: Lang;
  setLang: (lang: Lang) => void;
};

const LanguageContext = createContext<LanguageContextType>({
  lang: "en",
  setLang: () => {},
});

const STORAGE_KEY = "mylawfirmai_lang";

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored === "ms" || stored === "en" ? stored : "en";
  });

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
  }, [lang]);

  return (
    <LanguageContext.Provider value={{ lang, setLang }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}

export type TFunc = (key: string, vars?: Record<string, string | number>) => string;

export function useT(): TFunc {
  const { lang } = useContext(LanguageContext);
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const dict = dictionaries[lang];
      let str = dict[key] ?? en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
        }
      }
      return str;
    },
    [lang],
  );
}

const DATE_LOCALES: Record<Lang, Locale> = { en: enUS, ms: msLocale };

/** Locale-aware date formatter that follows the current language. */
export function useFormatDate() {
  const { lang } = useContext(LanguageContext);
  return useCallback(
    (date: Date | number | string, fmt: string) =>
      dfFormat(new Date(date), fmt, { locale: DATE_LOCALES[lang] }),
    [lang],
  );
}

/** Convenience hook for dynamic enum labels. */
export function useLabels() {
  const t = useT();
  return {
    status: (s: string) => t(`status.${s}`),
    category: (c: string) => t(`category.${c}`),
    reason: (r: string) => t(`reason.${r}`),
    role: (r: string) => t(`common.role.${r}`),
  };
}
